 const {data: integration,error:integrationError}=await db.from('integrations').select('id').eq('website_id',fixture.mvp.websiteId).eq('provider','wordpress').single();
 if(integrationError)throw integrationError;
 const remoteUrl='https://browser-member.example/wp-admin/post.php?post=9286&action=edit';
 const {error:transferError}=await db.from('cms_transfers').insert({website_id:fixture.mvp.websiteId,integration_id:integration.id,article_key:`${prior.id}:${original.keyword}`,content_hash:'synthetic-recovery-286',remote_id:'9286',remote_edit_url:remoteUrl,status:'succeeded',publication_status:'delivered_draft',remote_status:'draft',completed_at:new Date().toISOString()});
 if(transferError)throw transferError;
 await page.reload();
 await expect(page.getByRole('button',{name:'Reopen this draft',exact:true})).toBeVisible();
 await expect(page.getByRole('link',{name:'Open WordPress editor',exact:true})).toHaveAttribute('href',remoteUrl);
 await expect(page.getByRole('button',{name:'Update WordPress draft',exact:true})).toBeVisible();
