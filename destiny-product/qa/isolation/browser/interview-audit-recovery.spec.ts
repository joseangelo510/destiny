 const edited=(await box.inputValue())+'\n\nSaved provenance check.';
 await box.fill(edited);
 releaseHydration();
 await expect.poll(async()=>{
  const {data}=await db.from('article_drafts').select('draft').eq('interview_id',interviewId).single();
  return data?.draft?.body;
 }).toBe(edited);
 const {data:duplicates,error:duplicateError}=await db.from('article_drafts').select('id').eq('audit_id',newer.id);
 if(duplicateError)throw duplicateError;
 expect(duplicates).toEqual([]);
 console.log('EDIT_SAVED_TO_ORIGINAL_AUDIT_WITH_NO_NEW_AUDIT_DUPLICATE');
