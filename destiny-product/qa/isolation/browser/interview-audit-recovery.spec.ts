 await page.getByRole('button',{name:'Save answer & continue →',exact:true}).click();
 for(let n=2;n<=7;n++){
  await expect(page.getByText(`Question ${n} of 7`,{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Skip this question',exact:true}).click();
 }
 await expect(page.getByRole('heading',{name:'Here is what Rebound SEO captured.',exact:true})).toBeVisible();
 await expect(page.getByRole('blockquote').filter({hasText:words}).first()).toHaveText(words);
 const {data: prior,error:readError}=await db.from('audits').select('id,website_id,requested_by,provider').eq('website_id',fixture.mvp.websiteId).eq('status','complete').order('created_at',{ascending:false}).limit(1).single();
 if(readError)throw readError;
 const {data: newer,error:newError}=await db.from('audits').insert({website_id:prior.website_id,requested_by:prior.requested_by,provider:prior.provider,status:'complete',progress:100,completed_at:new Date().toISOString()}).select('id').single();
 if(newError)throw newError;
 const {data:metric,error:metricError}=await db.from('audit_metrics').select('*').eq('audit_id',fixture.mvp.auditId).single();
 if(metricError)throw metricError;
 const {id:oldMetricId,created_at:oldMetricCreated,updated_at:oldMetricUpdated,...metricFields}=metric;
 const {error:copyError}=await db.from('audit_metrics').insert({...metricFields,audit_id:newer.id});
 if(copyError)throw copyError;
 console.log(JSON.stringify({priorAudit:prior.id,newAudit:newer.id}));
 await page.getByRole('button',{name:'Write my article from this →',exact:true}).click();
 await expect(page).toHaveURL(/\/content\?interview=/);
 const interviewId=new URL(page.url()).searchParams.get('interview');
 const {data:saved,error:savedError}=await db.from('article_drafts').select('audit_id,interview_id').eq('interview_id',interviewId);
 if(savedError)throw savedError;
 console.log(JSON.stringify({savedDraftLinks:saved,destination:page.url()}));
 await expect(page.getByText('Interview draft ready',{exact:true})).toBeVisible();
 await expect(page.getByRole('textbox',{name:'Article draft',exact:true})).toHaveValue(new RegExp(words.replace(/[.*+?^${}()|[\]\\]/g,'\\$&')));
