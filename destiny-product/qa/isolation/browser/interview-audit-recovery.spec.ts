 await expect(page.getByText('Interview draft ready',{exact:true})).toBeVisible();
 await expect(box).toHaveValue(edited);
 const {data: original,error:originalError}=await db.from('article_drafts').select('*').eq('interview_id',interviewId).single();
 if(originalError)throw originalError;
 const {error:approvalSeedError}=await db.from('article_drafts').update({draft:{...original.draft,generationStatus:'generated',generatedBy:'synthetic-local-fixture',body:edited+'\n\n'+('Synthetic audit provenance fixture content. '.repeat(380)),metaTitle:original.keyword,titleCandidates:['numbered','how_to','second_person','question','descriptive','benefit'].map(format=>({format,headline:original.keyword,metaTitle:original.keyword,score:80,rationale:'Synthetic fixture'})),qualityIssues:[],approved:true}}).eq('id',original.id);
